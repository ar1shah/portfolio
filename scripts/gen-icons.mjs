/**
 * Emits src/components/skills/icon-paths.ts.
 *
 * Why generate instead of importing simple-icons at runtime: the package is
 * ~3000 icons. We need 30. Baking the path strings into a module keeps the
 * client bundle to a few KB and lets simple-icons stay a devDependency.
 *
 * Four marks (Java, AWS, OpenAI, Twilio) were dropped from current
 * simple-icons over trademark policy, so they live in legacy-icons.json,
 * extracted from older releases. Run: node scripts/gen-icons.mjs
 */
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const legacy = JSON.parse(
  readFileSync(resolve(here, "legacy-icons.json"), "utf8"),
);
const si = await import("simple-icons");

/**
 * `hex` overrides exist because several brands are near-black, which is
 * invisible against #0B0B0C on hover. Those get a legible stand-in.
 */
const SET = [
  { slug: "typescript", label: "TypeScript", group: "lang" },
  { slug: "javascript", label: "JavaScript", group: "lang" },
  { slug: "java", label: "Java", group: "lang", legacy: true },
  { slug: "cplusplus", label: "C++", group: "lang" },
  { slug: "python", label: "Python", group: "lang" },
  { slug: "html5", label: "HTML5", group: "lang" },
  { slug: "css", label: "CSS", group: "lang" },
  { slug: "go", label: "Go", group: "lang" },

  { slug: "react", label: "React", group: "framework" },
  { slug: "nextdotjs", label: "Next.js", group: "framework", hex: "EDEAE4" },
  { slug: "nodedotjs", label: "Node.js", group: "framework" },
  { slug: "express", label: "Express", group: "framework", hex: "EDEAE4" },
  { slug: "flutter", label: "Flutter", group: "framework" },
  { slug: "dart", label: "Dart", group: "framework" },
  { slug: "tailwindcss", label: "Tailwind CSS", group: "framework" },

  { slug: "docker", label: "Docker", group: "tool" },
  { slug: "git", label: "Git", group: "tool" },
  { slug: "github", label: "GitHub", group: "tool", hex: "EDEAE4" },
  { slug: "amazonaws", label: "AWS", group: "tool", legacy: true, hex: "FF9900" },
  { slug: "supabase", label: "Supabase", group: "tool" },
  { slug: "vite", label: "Vite", group: "tool" },
  { slug: "vercel", label: "Vercel", group: "tool", hex: "EDEAE4" },
  { slug: "figma", label: "Figma", group: "tool" },
  { slug: "arduino", label: "Arduino", group: "tool" },

  { slug: "mongodb", label: "MongoDB", group: "data" },
  { slug: "mysql", label: "MySQL", group: "data" },
  { slug: "postgresql", label: "PostgreSQL", group: "data" },
  { slug: "twilio", label: "Twilio", group: "data", legacy: true },
  { slug: "openai", label: "OpenAI", group: "data", legacy: true, hex: "EDEAE4" },
  { slug: "axios", label: "Axios", group: "data" },
];

const key = (slug) => "si" + slug.charAt(0).toUpperCase() + slug.slice(1);

const rows = [];
const missing = [];

for (const item of SET) {
  const src = item.legacy ? legacy[item.slug] : si[key(item.slug)];
  if (!src?.path) {
    missing.push(item.slug);
    continue;
  }
  rows.push({
    slug: item.slug,
    label: item.label,
    group: item.group,
    hex: item.hex ?? src.hex,
    path: src.path,
  });
}

if (missing.length) {
  console.error("Missing marks, aborting:", missing.join(", "));
  process.exit(1);
}

const out = `// GENERATED by scripts/gen-icons.mjs — do not edit by hand.
// Regenerate with: node scripts/gen-icons.mjs

export type IconGroup = "lang" | "framework" | "tool" | "data";

export type Icon = {
  slug: string;
  label: string;
  group: IconGroup;
  /** Brand color, hex without the #. Overridden where the real one is
   *  too dark to read against the page ground. */
  hex: string;
  /** 24x24 viewBox path data. */
  path: string;
};

export const icons: Icon[] = ${JSON.stringify(rows, null, 2)};
`;

const dest = resolve(here, "../src/components/skills/icon-paths.ts");
writeFileSync(dest, out);
console.log(`Wrote ${rows.length} icons to ${dest}`);
