/**
 * Bakes a land/ocean bitmask from Natural Earth coastlines into
 * src/components/hero/land-mask.ts.
 *
 * Real geography rather than hand-drawn continents: the globe has to be
 * recognizable at a glance, and eyeballed coastlines are exactly the kind
 * of thing that reads as slightly wrong without anyone being able to say
 * why.
 *
 * One bit per cell, packed into bytes and base64'd. A 1-degree grid is
 * 360x180 = 64,800 bits = 8.1KB, which is far finer than a ~96-column
 * globe can resolve, so the mask never limits the render.
 *
 * Run: node scripts/bake-land.mjs [lonCells] [latCells]
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));

const LON_CELLS = Number(process.argv[2] ?? 360);
const LAT_CELLS = Number(process.argv[3] ?? 180);

const topology = require("world-atlas/land-110m.json");
const land = feature(topology, topology.objects.land);

console.log(`source      : world-atlas land-110m (${topology.arcs.length} arcs)`);
console.log(`grid        : ${LON_CELLS} x ${LAT_CELLS} (${LON_CELLS * LAT_CELLS} cells)`);

const bits = new Uint8Array(Math.ceil((LON_CELLS * LAT_CELLS) / 8));
let landCount = 0;

for (let j = 0; j < LAT_CELLS; j++) {
  // Sample cell centres. Latitude runs +90 at row 0 down to -90.
  const lat = 90 - ((j + 0.5) / LAT_CELLS) * 180;
  for (let i = 0; i < LON_CELLS; i++) {
    const lon = -180 + ((i + 0.5) / LON_CELLS) * 360;
    if (!geoContains(land, [lon, lat])) continue;
    const idx = j * LON_CELLS + i;
    bits[idx >> 3] |= 128 >> (idx & 7);
    landCount++;
  }
}

const pct = ((landCount / (LON_CELLS * LAT_CELLS)) * 100).toFixed(1);
console.log(`land cells  : ${landCount.toLocaleString()} (${pct}% — Earth is ~29% land, but equirectangular over-weights the poles)`);

const b64 = Buffer.from(bits).toString("base64");

const out = `// GENERATED by scripts/bake-land.mjs — do not edit by hand.
// Source: world-atlas land-110m (Natural Earth, public domain)
// Regenerate: node scripts/bake-land.mjs ${LON_CELLS} ${LAT_CELLS}

/**
 * Land/ocean bitmask on an equirectangular grid, one bit per cell, packed
 * MSB-first and base64'd. Row 0 is +90 latitude, column 0 is -180 longitude.
 */
export const LAND = {
  lonCells: ${LON_CELLS},
  latCells: ${LAT_CELLS},
  bits: "${b64}",
} as const;
`;

const dest = resolve(here, "../src/components/hero/land-mask.ts");
writeFileSync(dest, out);
console.log(`encoded     : ${(bits.length / 1024).toFixed(1)}KB raw -> ${(b64.length / 1024).toFixed(1)}KB base64`);
console.log(`wrote       : ${dest}`);
